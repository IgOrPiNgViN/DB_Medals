def normalize_button_text(text: str) -> str:
    return text.strip().replace("…", "").replace("\u2026", "").strip()


def button_help(page_key: str, button_text: str) -> str:
    clean = normalize_button_text(button_text)
    if not clean:
        return COMMON_BUTTON_HELP["_default"]
    key = (page_key, clean)
    if key in BUTTON_HELP:
        return BUTTON_HELP[key]
    if clean in COMMON_BUTTON_HELP:
        return COMMON_BUTTON_HELP[clean]
    for label, help_text in COMMON_BUTTON_HELP.items():
        if label == "_default":
            continue
        if clean.startswith(label) or label.startswith(clean):
            return help_text
    return COMMON_BUTTON_HELP["_default"]


