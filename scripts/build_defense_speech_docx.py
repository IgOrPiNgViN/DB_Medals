    _add_para(
        doc,
        "На титульном слайде указаны реквизиты работы и тема. "
        "Она отражает суть проекта: мы создавали не абстрактную «базу данных», "
        "а рабочий инструмент для людей, которые каждый день ведут учёт наград, "
        "лауреатов и заседаний наградного комитета.",
    )

